import React, {useCallback, useState} from 'react';
import {Image, Pressable, StyleSheet, Text, View} from 'react-native';
import {PlayerScreen} from './screens/PlayerScreen';
import {setLogger} from 'react-native-tv-audio-description';
import {createVegaAdapter} from 'react-native-tv-audio-description/vega';
import {log} from './diagnostics';
import {E2E, type E2EConfig} from './e2e';
import type {AssetSource, MediaAdapter} from 'react-native-tv-audio-description';

// Required rather than referenced by string so that metro bundles it into the
// package: `mp4` is in metro's default assetExts, and the build's asset-copy
// step only has something to copy when an asset is actually required. The media
// pipeline runs in its own process and cannot reach the host through the app's
// port forwarding (limits.vega_media.media_process_is_separate), so the asset
// has to travel inside the package.
//
// NOTE the directory: src/assets/, NOT the project-root assets/. The Vega build
// copies the project-root assets/ directory verbatim into the package
// (limits.vega_media.build_packages_assets_dir), which is how 489 MB of source
// film once shipped to the device.
const CLIP = require('./assets/clip.mp4');

// One synthesised description cue, here to answer defects[D6] and defects[D2]
// on a real device. changes[C10] replaces it with Polly output; the container is
// already what C10 must emit — fragmented mp4, AAC-LC.
const CUE = require('./assets/cue.m4a');

/**
 * The segments, GENERATED by pipeline/prepare.ts — timings and all.
 *
 * Metro resolves `require` at build time, so the app cannot read a manifest and
 * require what it names: a path computed at runtime bundles nothing, and the
 * failure lands on the device as a fetch for a file that is not in the package.
 * The pipeline therefore emits the static requires, and the timings come from
 * the HLS playlist ffmpeg actually produced rather than from the length that was
 * asked for (limits.mse_buffer.segment_uneven).
 *
 * Until R37 this was four requires hand-written here, which drifted the moment
 * anybody re-cut the asset.
 */
import {INIT, SEGMENTS} from './assets/seg/segments';

const resolved = Image.resolveAssetSource(CLIP);

/**
 * The demo clip as a one-segment asset.
 *
 * A whole-file asset is a single segment covering the whole timeline, so it
 * takes the same path through limits.mse_buffer as a segmented one. That is
 * deliberate: if the short clip took a separate "just append it" path, the
 * windowing code would only ever run on the asset nobody tests with.
 *
 * changes[C10] emits the segmented form, and then this becomes
 * contracts.asset_manifest.segments read from the track's manifest.
 */
const DEMO_ASSET = {
  initUri: Image.resolveAssetSource(INIT)?.uri ?? '',
  segments: SEGMENTS.map(s => ({
    index: s.index,
    start_ms: s.start_ms,
    end_ms: s.end_ms,
    uri: Image.resolveAssetSource(s.mod)?.uri ?? '',
  })),
};
log(
  `INTERSTICE.asset.segments n=${DEMO_ASSET.segments.length}` +
    ` init=${DEMO_ASSET.initUri ? 'set' : 'NONE'}`,
);
const resolvedCue = Image.resolveAssetSource(CUE);
log(`INTERSTICE.asset.resolved uri=${resolved?.uri ?? 'NONE'}`);
log(`INTERSTICE.asset.cue uri=${resolvedCue?.uri ?? 'NONE'}`);

// The description layer and its Vega adapter are changes[C12], consumed from
// npm. Its diagnostic lines arrive unprefixed; they join the INTERSTICE.* lines
// here, over the same beacon (limits.vega_media.no_js_console).
setLogger(line => log(`INTERSTICE.${line}`));

// Which build this is, in every launch of either build. S01 asserts e2e=false
// on the Release package, and AC15 asserts it again after a VARIANT run.
log(`INTERSTICE.app.mode e2e=${E2E !== null} host=${E2E?.host ?? 'none'}`);

/**
 * The one place the platform is chosen. Everything else in src/ reaches the
 * device only through the object this returns — enforced by
 * pipeline/__tests__/seam.test.ts, not by good intentions.
 *
 * ONE ADAPTER PER OPEN, never one per module. The package's contract is one
 * adapter per screen (its README: `useMemo(() => createVegaAdapter(), [])`
 * inside the player), and its Vega adapter is single-use in practice: after
 * `destroy()` has deinitialized the native player, `open()` on the same object
 * attaches a MediaSource to a player that no longer exists and `sourceopen`
 * never fires — no append, no `player.opened`, no error, forever. That was
 * `docs/features/e2e-harness/_facts.yml` defects[D8], measured five of five
 * on the Virtual Device: a module-scope adapter here was reused after BACK,
 * and the second open of the same title sat on "Loading" for 20 s. A fresh
 * adapter per open is what the package asks for, and it is also what makes
 * the second open indistinguishable from the first.
 */
const openMedia = (): MediaAdapter => createVegaAdapter();


/**
 * One title. `decisions.demo_asset_licensing` — openly licensed, dialogue
 * bearing, and recorded with its license in README.md.
 */
const TITLES = [
  {id: 'tears-of-steel', label: 'Tears of Steel'},
  // VARIANT build only. The label is limits.fixture.title_label, verbatim: if
  // this build is ever on screen when it should not be, it says so itself.
  ...(E2E ? [{id: E2E.asset_id, label: 'E2E FIXTURE — not a film'}] : []),
];

/**
 * Track files sit beside the asset and are fetched like any other packaged file.
 * `limits.vega_media.url_mode_broken` is about the PLAYER, not about fetch —
 * JavaScript reaches packaged paths fine, which R18 measured before anything
 * else worked.
 *
 * The package's loader reads EVERY throw from this function as absence
 * (`loader.miss`, then "No description track was found"). So a throw here must
 * mean the file is not there — a non-2xx status, or fetch itself rejecting —
 * and nothing else. A file that IS there but is not JSON is a different
 * failure with a different sentence (AC8, `02e` Part C §C.6: a truncated
 * track gets "could not be read", not "was not found"), and that sentence is
 * reachable only by handing the loader a value its validator rejects. The raw
 * text is that value: it is what was read, and it is not an object.
 * `docs/features/e2e-harness/_facts.yml` defects[D9] is what happened while
 * this function threw on the parse failure too.
 */
export async function readJson(path: string): Promise<unknown> {
  const response = await fetch(path);
  if (!response.ok) throw new Error(`HTTP ${response.status}`);
  const text = await response.text();
  try {
    return JSON.parse(text) as unknown;
  } catch (err) {
    log(`INTERSTICE.app.unparseable path=${path} err=${(err as Error).message}`);
    return text;
  }
}

type Playing = {
  id: string;
  asset: AssetSource;
  assetDir: string;
  cueUri: string;
  /** this open's adapter — see openMedia() */
  media: MediaAdapter;
};

/** contracts.fixture_asset, read from the host and resolved against it */
async function fixtureAsset(e2e: E2EConfig): Promise<AssetSource> {
  const layout = (await readJson(`${e2e.segment_base}/asset.json`)) as {
    init: string;
    segments: {index: number; start_ms: number; end_ms: number; uri: string}[];
  };
  return {
    initUri: `${e2e.segment_base}/${layout.init}`,
    segments: layout.segments.map(s => ({
      ...s,
      uri: `${e2e.segment_base}/${s.uri}`,
    })),
  };
}

export const App = () => {
  const [playing, setPlaying] = useState<Playing | null>(null);
  const exit = useCallback(() => setPlaying(null), []);

  const start = useCallback(async (id: string) => {
    log(`INTERSTICE.app.play id=${id}`);
    if (E2E && id === E2E.asset_id) {
      try {
        // no probe cue here: the only cues that fire are the fixture track's
        setPlaying({
          id,
          asset: await fixtureAsset(E2E),
          assetDir: E2E.asset_dir,
          cueUri: '',
          media: openMedia(),
        });
      } catch (err) {
        log(`INTERSTICE.app.fixture failed err=${(err as Error).message}`);
      }
      return;
    }
    setPlaying({
      id,
      asset: DEMO_ASSET,
      assetDir: '/pkg/bundle/assets/src/assets',
      cueUri: resolvedCue?.uri ?? '',
      media: openMedia(),
    });
  }, []);

  if (playing) {
    return (
      <PlayerScreen
        media={playing.media}
        asset={playing.asset}
        cueUri={playing.cueUri}
        assetDir={playing.assetDir}
        assetId={playing.id}
        readJson={readJson}
        onExit={exit}
      />
    );
  }

  return (
    <View style={styles.list}>
      <Text style={styles.heading}>Interstice</Text>
      {TITLES.map((title, index) => (
        <Pressable
          key={title.id}
          accessible
          accessibilityRole="button"
          accessibilityLabel={`Play ${title.label}`}
          hasTVPreferredFocus={index === 0}
          onPress={() => void start(title.id)}>
          <Text style={styles.title}>{title.label}</Text>
        </Pressable>
      ))}
    </View>
  );
};

const styles = StyleSheet.create({
  list: {flex: 1, backgroundColor: '#000', padding: 48, gap: 24},
  heading: {color: '#fff', fontSize: 48, marginBottom: 24},
  title: {color: '#fff', fontSize: 32},
});

export default App;
